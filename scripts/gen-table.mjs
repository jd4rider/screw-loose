// Finds, for every level, the generator attempt that yields a verified-solvable board and its solution length.
import { writeFileSync } from 'node:fs'
import { build, solve, startState, TOTAL_LEVELS } from '../src/game.js'

const rows = []
for (let n = 1; n <= TOTAL_LEVELS; n++) {
  let found = null
  for (let attempt = 0; attempt < 200 && !found; attempt++) {
    const level = build(n, attempt)
    if (level.panels.length < 2) continue
    const res = solve(level, startState(level), 20000)
    if (res.path && res.path.length >= Math.min(level.panels.length, 3)) found = [attempt, res.path.length]
  }
  if (!found) throw new Error(`no solvable board for level ${n}`)
  rows.push(found)
}
writeFileSync(new URL('../src/levels-table.js', import.meta.url), `// Generated by scripts/gen-table.mjs - [generator attempt, solution length] per level.\nexport default ${JSON.stringify(rows)}\n`)
console.log('wrote', rows.length)
